// ============================================================
// GAMEHUB - ROUTER
// ============================================================

window.GameHub = window.GameHub || {};

window.GameHub.router = {

    // --------------------------------------------------------
    // Переход к модулю
    // --------------------------------------------------------

    go(module, path = "") {

        let url = `../${module}/`;

        if (path) {
            url += path;
        }

        window.location.href = url;
    },


    // --------------------------------------------------------
    // Переход на главную
    // --------------------------------------------------------

    home() {

        window.location.href = "/GameHub/";
    },


    // --------------------------------------------------------
    // Открыть профиль
    // --------------------------------------------------------

    profile(userId = "") {

        if (userId) {

            window.location.href =
                `../profile/?id=${encodeURIComponent(userId)}`;

            return;
        }

        window.location.href = "../profile/";
    },


    // --------------------------------------------------------
    // Игры
    // --------------------------------------------------------

    games() {

        window.location.href = "../games/";
    },


    // --------------------------------------------------------
    // Гильдии
    // --------------------------------------------------------

    guilds() {

        window.location.href = "../guilds/";
    },


    // --------------------------------------------------------
    // Чат
    // --------------------------------------------------------

    chat() {

        window.location.href = "../chat/";
    },


    // --------------------------------------------------------
    // Конференция
    // --------------------------------------------------------

    conference() {

        window.location.href = "../conference/";
    }

};